import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from statsmodels.formula.api import ols
np.random.seed(101)

data = pd.read_csv('Advertising.csv', header=(0), index_col=[0])
data = data[['radio','sales']]
y_label = data.columns[-1]
print('Número de linhas e colunas', data.shape)
data.head()

# Ajustando o modelo de regressão linear
modelo = ols('sales ~ radio', data=data).fit()

# Mostra o resumo do modelo
modelo.summary()

#Obtendo os coeficientes
intercepto = modelo.params['Intercept']
coeficiente_radio = modelo.params['radio']

print(f"Intercepto: {intercepto:.4f}")
print(f"Coeficiente do radio: {coeficiente_radio:.4f}")
print('Modelo ajustado:')
print(f'\n sales = {intercepto:.4f} + {coeficiente_radio:.4f} * radio')

data['sales_predito'] = modelo.predict(data)
display(data.head(10))

# Ordenando os valores dos dados conforme radio,
# para evitar linhas cruzadas no gráfico
data_ordenado = data.sort_values('radio')

plt.figure(figsize=(10, 6))
# Dados observados
plt.scatter(
    data['radio'],
    data['sales'],
    alpha = 0.7,
    label='Dados Observados'
)
# Reta de Regressão
plt.plot(
    data_ordenado['radio'],
    data_ordenado['sales_predito'],
    linewidth = 2.5,
    label='Modelo de regressão linear ajustado'
)

plt.xlabel('Investimento em propagando no radio')
plt.ylabel('Vendas')
plt.title('Investimento em radio versus vendas')
plt.legend()
plt.grid(alpha=0.3)
plt.show()
#

print(f"R²: {modelo.rsquared:.4f}")
print(f"R² ajustado: {modelo.rsquared_adj:.4f}")
print(f"Erro quadrático médio dos resíduos: {modelo.mse_resid:.4f}")